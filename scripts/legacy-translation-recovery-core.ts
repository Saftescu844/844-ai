import type { Payload } from 'payload'
import type { TraducereRezultat } from '../translator'

type Translate = (source: {
  titlu: string
  excerpt: string
  continut: unknown
}) => Promise<TraducereRezultat | null>

export type RecoveryDeps = {
  payload: Payload
  translate: Translate
  slugEnglish: (title: string) => string
}

export type RecoveryOutcome =
  | { kind: 'dry-run'; articleId: number; existingEnglishId: number | null }
  | { kind: 'relinked'; articleId: number; englishId: number }
  | { kind: 'created'; articleId: number; englishId: number }

/**
 * No writes or external model requests are made when apply=false.
 * The CLI takes a per-article PostgreSQL advisory lock before invoking this
 * function with apply=true, to serialize independent recovery processes.
 */
export async function recoverLegacyTranslation(
  { payload, translate, slugEnglish }: RecoveryDeps,
  articleId: number,
  apply: boolean,
): Promise<RecoveryOutcome> {
  const source = await payload.findByID({
    collection: 'articole', id: articleId, draft: true, depth: 0,
  })
  const publishedView = await payload.findByID({
    collection: 'articole', id: articleId, draft: false, depth: 0,
  })

  if (source.limba !== 'ro' || source._status !== 'draft'
    || source.editorialStatus !== 'review' || source.generatAutomat !== true
    || publishedView._status === 'published') {
    throw new Error('Recovery only supports unpublished, autogenerated RO review drafts')
  }
  if (!source.sursaLink || !source.excerpt?.trim() || !source.continut) {
    throw new Error('Missing source URL, excerpt or content; manual editorial review required')
  }

  const linkedId = typeof source.versiuneAlternativa === 'object'
    ? source.versiuneAlternativa?.id : source.versiuneAlternativa
  if (linkedId) throw new Error('RO article already has a linked partner; refusing recovery')

  const reverse = await payload.find({
    collection: 'articole', depth: 0, draft: true, limit: 2,
    where: { versiuneAlternativa: { equals: articleId } },
  })
  if (reverse.totalDocs > 1 || reverse.docs.some((doc) => doc.limba !== 'en')) {
    throw new Error('Ambiguous reverse language links; manual review required')
  }
  const partner = reverse.docs[0]
  const bySource = await payload.find({
    collection: 'articole', depth: 0, draft: true, limit: 2,
    where: { and: [
      { limba: { equals: 'en' } },
      { sursaLink: { equals: source.sursaLink } },
    ] },
  })
  if (bySource.totalDocs > 1
    || bySource.docs.some((doc) => !partner || doc.id !== partner.id)) {
    throw new Error('An EN article with the same source URL exists; review before creating another')
  }

  if (!apply) {
    return { kind: 'dry-run', articleId, existingEnglishId: partner?.id ?? null }
  }

  if (partner) {
    const existingLive = await payload.findByID({
      collection: 'articole', id: partner.id, draft: false, depth: 0,
    })
    if (partner._status !== 'draft' || existingLive._status === 'published') {
      throw new Error('Existing EN partner is published; manual review required')
    }
    await payload.update({
      collection: 'articole', id: articleId, draft: true,
      data: { versiuneAlternativa: partner.id },
    })
    return { kind: 'relinked', articleId, englishId: partner.id }
  }

  const translated = await translate({
    titlu: source.titlu,
    excerpt: source.excerpt,
    continut: source.continut,
  })
  if (!translated?.titlu?.trim() || !translated.excerpt?.trim() || !translated.continut) {
    throw new Error('Translation incomplete; RO draft unchanged')
  }

  // A concurrent editorial edit invalidates the translation source.
  const freshSource = await payload.findByID({
    collection: 'articole', id: articleId, draft: true, depth: 0,
  })
  if (freshSource.updatedAt !== source.updatedAt || freshSource.versiuneAlternativa) {
    throw new Error('RO draft changed during translation; abort')
  }
  const freshReverse = await payload.find({
    collection: 'articole', draft: true, depth: 0, limit: 1,
    where: { versiuneAlternativa: { equals: articleId } },
  })
  if (freshReverse.totalDocs > 0) throw new Error('EN partner appeared; abort')

  const tags = Array.isArray(source.tags)
    ? source.tags.filter((item) => typeof item.tag === 'string' && item.tag.trim())
      .map((item) => ({ tag: item.tag }))
    : []

  const created = await payload.create({
    collection: 'articole', draft: true,
    data: {
      titlu: translated.titlu,
      slug: slugEnglish(translated.titlu),
      limba: 'en',
      pilon: typeof source.pilon === 'object' ? source.pilon.id : source.pilon,
      tip: source.tip,
      excerpt: translated.excerpt.substring(0, 298),
      continut: translated.continut,
      sursaNume: source.sursaNume,
      sursaLink: source.sursaLink,
      ...(tags.length ? { tags } : {}),
      ...(source.numarConfirmari ? { numarConfirmari: source.numarConfirmari } : {}),
      ...(source.imaginePrincipala ? {
        imaginePrincipala: typeof source.imaginePrincipala === 'object'
          ? source.imaginePrincipala.id : source.imaginePrincipala,
      } : {}),
      editorialStatus: 'review',
      generatAutomat: true,
      versiuneAlternativa: articleId,
      metaTitle: translated.metaTitle.substring(0, 58),
      metaDescription: translated.metaDescription.substring(0, 158),
      ...(source.subcategorie ? { subcategorie: source.subcategorie } : {}),
      ...(source.subcategorieEducatie ? { subcategorieEducatie: source.subcategorieEducatie } : {}),
    } as any,
  })
  try {
    await payload.update({
      collection: 'articole', id: articleId, draft: true,
      data: { versiuneAlternativa: created.id },
    })
  } catch (error) {
    throw new Error(`EN draft ${created.id} created but RO backlink failed; re-run after review`, {
      cause: error,
    })
  }
  return { kind: 'created', articleId, englishId: created.id }
}
